CREATE TABLE IF NOT EXISTS users (
 id INTEGER PRIMARY KEY, username TEXT COLLATE NOCASE NOT NULL UNIQUE, email_key TEXT NOT NULL UNIQUE,
 salt BLOB NOT NULL, verifier BLOB NOT NULL, kills INTEGER NOT NULL DEFAULT 0, deaths INTEGER NOT NULL DEFAULT 0,
 wins INTEGER NOT NULL DEFAULT 0, score INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires REAL NOT NULL);
CREATE INDEX IF NOT EXISTS session_user ON sessions(user_id,expires);
CREATE TABLE IF NOT EXISTS limits (
 key TEXT PRIMARY KEY, expires REAL NOT NULL, uses INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS limit_expiry ON limits(expires);
CREATE TABLE IF NOT EXISTS runs (
 id TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 created REAL NOT NULL, seen REAL NOT NULL, state TEXT NOT NULL, phase TEXT NOT NULL DEFAULT 'playing',
 ticks INTEGER NOT NULL DEFAULT 0, seq INTEGER NOT NULL DEFAULT 0, kills INTEGER NOT NULL DEFAULT 0,
 assists INTEGER NOT NULL DEFAULT 0, boss_assist INTEGER NOT NULL DEFAULT 0, score INTEGER NOT NULL DEFAULT 0);
CREATE UNIQUE INDEX IF NOT EXISTS current_run ON runs(user_id) WHERE phase='playing';
CREATE INDEX IF NOT EXISTS run_expiry ON runs(phase,seen);
CREATE INDEX IF NOT EXISTS score_sort ON users(score DESC,kills DESC,wins DESC,id);
